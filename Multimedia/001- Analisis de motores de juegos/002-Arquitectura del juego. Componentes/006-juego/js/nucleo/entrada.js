// Entrada
document.addEventListener("keydown", function(event) {
  switch (event.key) {
    case "w":
      console.log("UP");
      break;

    case "s":
      console.log("DOWN");
      break;

    case "a":
      console.log("LEFT");
      break;

    case "d":
      console.log("RIGHT");
      break;
  }
});
document.addEventListener("keyup", function(event) {
  switch (event.key) {
    case "w":
      console.log("UP");
      break;

    case "s":
      console.log("DOWN");
      break;

    case "a":
      console.log("LEFT");
      break;

    case "d":
      console.log("RIGHT");
      break;
  }
});